"""Turn TTS output into data.js for the composition.

Reads <video>/transcript.json and timings.json, writes <video>/data.js with:
  WORDS    [[text, start, end], ...]
  CAPTIONS [{start, end, words: [index, ...]}, ...]  short phrases for on-screen captions
  PHASES   {id: {start, end}}
  DURATION total seconds
and <video>/captions.srt.

Caption grouping: at most 6 words and 2.5 s per group; break at a pause >= 0.5 s
or a sentence end; never leave a single word alone at the end of a sentence.

Usage: python -I tools/build_data.py videos/<slug>
"""
import json
import sys
from pathlib import Path

MAX_WORDS = 6
MAX_SPAN = 2.5
PAUSE = 0.5


def group(words):
    groups, cur = [], []
    for i, w in enumerate(words):
        if cur:
            first, prev = words[cur[0]], words[cur[-1]]
            if (len(cur) >= MAX_WORDS or w["end"] - first["start"] > MAX_SPAN
                    or w["start"] - prev["end"] >= PAUSE or prev["end_of_sentence"]):
                groups.append(cur)
                cur = []
        cur.append(i)
    if cur:
        groups.append(cur)
    # Merge a lone trailing word into the previous group of the same sentence.
    merged = []
    for g in groups:
        if len(g) == 1 and merged and not words[merged[-1][-1]]["end_of_sentence"] and len(merged[-1]) < MAX_WORDS + 1:
            merged[-1] = merged[-1] + g
        else:
            merged.append(g)
    return merged


def srt_time(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3600000)
    m, ms = divmod(ms, 60000)
    s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def main(video_dir: Path) -> None:
    raw = json.loads((video_dir / "transcript.json").read_text(encoding="utf-8-sig"))
    timings = json.loads((video_dir / "timings.json").read_text(encoding="utf-8-sig"))
    script = json.loads((video_dir / "script.json").read_text(encoding="utf-8-sig"))

    # Kokoro tokens drop punctuation; recover sentence ends from the script lines.
    ends = []
    for p in script["phases"]:
        for line in p["lines"]:
            toks = [t for t in line.split() if any(c.isalnum() for c in t)]
            ends.extend([t.endswith((".", "?", "!")) or i == len(toks) - 1 for i, t in enumerate(toks)])
    words = []
    for i, w in enumerate(raw):
        words.append({**w, "end_of_sentence": ends[i] if i < len(ends) else False})

    caps = group(words)
    data = {
        "WORDS": [[w["word"], w["start"], w["end"]] for w in words],
        "CAPTIONS": [{"start": words[g[0]]["start"], "end": words[g[-1]]["end"], "words": g} for g in caps],
        "PHASES": {p["id"]: {"start": p["start"], "end": p["end"]} for p in timings["phases"]},
        "DURATION": timings["duration"],
    }
    js = "// Generated by tools/build_data.py. Do not edit by hand.\n" + "".join(
        f"window.{k} = {json.dumps(v)};\n" for k, v in data.items())
    (video_dir / "data.js").write_text(js, encoding="utf-8")

    srt = []
    for n, c in enumerate(data["CAPTIONS"], 1):
        text = " ".join(words[i]["word"] for i in c["words"])
        srt.append(f"{n}\n{srt_time(c['start'])} --> {srt_time(c['end'])}\n{text}\n")
    (video_dir / "captions.srt").write_text("\n".join(srt), encoding="utf-8")

    longest = max(len(c["words"]) for c in data["CAPTIONS"])
    print(json.dumps({"words": len(words), "captions": len(caps), "max_words_per_caption": longest,
                      "duration": data["DURATION"]}))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
