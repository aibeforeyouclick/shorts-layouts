"""Make 3 trial-reel versions of a short: same voice and body, a different hook screen over phase p1.

Reads <video>/script.json "trials": exactly 3 entries {"style", "text", "sub"} with 3 different
styles from headline / post / minimal. Needs data.js (tools/build_data.py) for PHASES.p1.
Writes:
  <video>/vendor/trial-hook.js    copy of tools/layouts/trial-hook.js
  <video>/trials.js               window.TRIALS = {A: ..., B: ..., C: ...}
and adds to index.html (once): the "trial" variable declaration on <html> (default "off" = control)
and the two <script> tags before </body>. One index.html only: HyperFrames lint allows one root file.

Render: npx --no-install hyperframes render --variables '{"trial":"A"}' -o out/<slug>-A.mp4
        (no --variables = the control version)
Usage: python -I tools/trial_reels.py videos/<slug>
"""
import json
import shutil
import sys
from pathlib import Path

STYLES = ("headline", "post", "minimal")
MAX_TEXT, MAX_SUB = 12, 8
VARS = """data-composition-variables='[{"id":"trial","type":"string","label":"Trial version (off/A/B/C)","default":"off"}]' """
TAGS = '    <script src="trials.js"></script>\n    <script src="vendor/trial-hook.js"></script>\n'
RUNTIME = Path(__file__).resolve().parent / "layouts" / "trial-hook.js"


def check(trials, data_js):
    errors = []
    if not isinstance(trials, list) or len(trials) != 3:
        return ["'trials' must be a list of exactly 3 entries"]
    styles = [t.get("style") for t in trials]
    for s in styles:
        if s not in STYLES:
            errors.append(f"unknown style {s!r}, use one of {STYLES}")
    if len(set(styles)) != 3:
        errors.append(f"styles must all differ: {styles}")
    for i, t in enumerate(trials):
        if not t.get("text") or not t.get("sub"):
            errors.append(f"trial {i + 1}: needs 'text' and 'sub'")
            continue
        if len(t["text"].split()) > MAX_TEXT:
            errors.append(f"trial {i + 1}: text over {MAX_TEXT} words")
        if len(t["sub"].split()) > MAX_SUB:
            errors.append(f"trial {i + 1}: sub over {MAX_SUB} words")
    if '"p1"' not in data_js:
        errors.append("data.js has no PHASES.p1: run tools/build_data.py first")
    return errors


def main(video_dir: Path) -> int:
    script = json.loads((video_dir / "script.json").read_text(encoding="utf-8-sig"))
    data_js = (video_dir / "data.js").read_text(encoding="utf-8") if (video_dir / "data.js").exists() else ""
    errors = check(script.get("trials"), data_js)
    if errors:
        for e in errors:
            print("ERROR  ", e)
        return 1

    (video_dir / "vendor").mkdir(exist_ok=True)
    shutil.copyfile(RUNTIME, video_dir / "vendor" / "trial-hook.js")
    keyed = dict(zip("ABC", script["trials"]))
    (video_dir / "trials.js").write_text(
        "// Generated by tools/trial_reels.py from script.json. Do not edit by hand.\n"
        f"window.TRIALS = {json.dumps(keyed)};\n", encoding="utf-8")

    index = video_dir / "index.html"
    html = index.read_text(encoding="utf-8")
    if "data-composition-variables" not in html:
        html = html.replace("<html ", "<html " + VARS, 1)
    elif '"id":"trial"' not in html:
        print("ERROR   index.html already declares variables; add the 'trial' declaration by hand")
        return 1
    if 'src="vendor/trial-hook.js"' not in html:
        if "  </body>" not in html:
            print("ERROR   index.html has no '  </body>' line to insert the script tags before")
            return 1
        html = html.replace("  </body>", TAGS + "  </body>", 1)
    index.write_text(html, encoding="utf-8")

    print(json.dumps({k: v["style"] for k, v in keyed.items()}))
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1])))
