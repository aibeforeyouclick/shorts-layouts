"""Shared helpers for the layout tools (ranking_list, storytelling, split_screen).

Each layout = a runtime in tools/layouts/<name>.js plus a data file <video>/<name>.data.js,
both loaded by two <script> tags added before </body> of index.html.
"""
import json
import re
import shutil
from pathlib import Path

LAYOUTS = Path(__file__).resolve().parent / "layouts"


def norm(word):
    return re.sub(r"[^a-z0-9']", "", word.lower())


def load(video_dir):
    script = json.loads((video_dir / "script.json").read_text(encoding="utf-8-sig"))
    html = (video_dir / "index.html").read_text(encoding="utf-8")
    t = video_dir / "transcript.json"
    words = json.loads(t.read_text(encoding="utf-8-sig")) if t.exists() else None
    return script, html, words


def check_phase(phase, html):
    if not phase or f'id="{phase}"' not in html:
        return [f"phase {phase!r}: no section with that id in index.html"]
    return []


def check_anchor(label, anchor, n, phase, words):
    """anchor must be spoken at least n times inside phase (words = transcript.json)."""
    if words is None:
        return [f"{label}: no transcript.json, run tools/tts.py first"]
    count = sum(1 for w in words if w.get("phase") == phase and norm(w["word"]) == norm(anchor or ""))
    return [] if count >= int(n or 1) else [f"{label}: anchor {anchor!r} #{n or 1} is not spoken in phase {phase}"]


def check_file(label, src, video_dir):
    if not src or Path(src).is_absolute() or ".." in Path(src).parts:
        return [f"{label}: {src!r} must be a relative path inside the video folder"]
    if not (video_dir / src).is_file():
        return [f"{label}: file {src!r} not found in the video folder"]
    return []


def install(video_dir, name, var, data, tool):
    """Copy the runtime, write the data file, add the script tags once. Returns an error string or None."""
    (video_dir / "vendor").mkdir(exist_ok=True)
    shutil.copyfile(LAYOUTS / f"{name}.js", video_dir / "vendor" / f"{name}.js")
    (video_dir / f"{name}.data.js").write_text(
        f"// Generated by tools/{tool} from script.json. Do not edit by hand.\n"
        f"window.{var} = {json.dumps(data)};\n", encoding="utf-8")
    index = video_dir / "index.html"
    html = index.read_text(encoding="utf-8")
    if f'src="vendor/{name}.js"' in html:
        return None
    if "  </body>" not in html:
        return "index.html has no '  </body>' line to insert the script tags before"
    tags = f'    <script src="{name}.data.js"></script>\n    <script src="vendor/{name}.js"></script>\n'
    index.write_text(html.replace("  </body>", tags + "  </body>", 1), encoding="utf-8")
    return None


def fail(errors):
    for e in errors:
        print("ERROR  ", e)
    return 1
